import { Polyline, MachinePreset, PenSlot } from '@/types/plotter';
import { penToNozzle, validateToolpath } from './validator';

export interface GcodeGenerationResult {
  gcode: string;
  lineCount: number;
  penCount: number;
  isValid: boolean;
  errors: string[];
  estimatedTimeSeconds: number;
}

function formatDuration(seconds: number): string {
  const m = Math.floor(seconds / 60);
  const s = seconds % 60;
  if (m === 0) return `${s}s`;
  const h = Math.floor(m / 60);
  const remM = m % 60;
  if (h === 0) return `${m}m ${s}s`;
  return `${h}h ${remM}m ${s}s`;
}

/**
 * Calculates safe physical nozzle position such that the mounted pen nib
 * is positioned over a safe plate area (at least 20mm inside safe bed bounds).
 */
export function getSafePenPausePosition(preset: MachinePreset): { nozzleX: number; nozzleY: number } {
  const safePenX = Math.max(20, Math.min(preset.bedWidth - 20, 25));
  const safePenY = Math.max(20, Math.min(preset.bedDepth - 20, 25));

  const nozzle = penToNozzle(safePenX, safePenY, preset.penOffsetX, preset.penOffsetY);

  const nozzleX = Math.max(preset.minSafeX, Math.min(preset.maxSafeX, nozzle.x));
  const nozzleY = Math.max(preset.minSafeY, Math.min(preset.maxSafeY, nozzle.y));

  return { nozzleX, nozzleY };
}

/**
 * Generates collision-safe, multi-pen pen plotter G-code for 3D printers and GRBL plotters.
 */
export function generateGcode(
  polylines: Polyline[],
  preset: MachinePreset,
  pens: PenSlot[] = []
): GcodeGenerationResult {
  // Validate first
  const validation = validateToolpath(polylines, preset);

  const penMap = new Map<string, PenSlot>();
  for (const pen of pens) {
    penMap.set(pen.id, pen);
  }

  // Group polylines by penId in order of first appearance, respecting enabled status
  const penGroups = new Map<string, Polyline[]>();
  for (const poly of polylines) {
    if (poly.points.length < 2) continue;
    const pen = penMap.get(poly.penId);
    if (pen && pen.enabled === false) continue; // Skip disabled pen layers
    const group = penGroups.get(poly.penId) || [];
    group.push(poly);
    penGroups.set(poly.penId, group);
  }

  const penKeys = Array.from(penGroups.keys());
  const penCount = Math.max(1, penKeys.length);

  // Calculate drawing distance and air travel for time estimation
  let totalDrawDist = 0;
  let totalAirDist = 0;
  let curPos = { x: preset.safeParkX, y: preset.safeParkY };

  for (const poly of polylines) {
    if (poly.points.length < 2) continue;
    const pStart = penToNozzle(poly.points[0].x, poly.points[0].y, preset.penOffsetX, preset.penOffsetY);
    const pEnd = penToNozzle(
      poly.points[poly.points.length - 1].x,
      poly.points[poly.points.length - 1].y,
      preset.penOffsetX,
      preset.penOffsetY
    );

    const dxAir = pStart.x - curPos.x;
    const dyAir = pStart.y - curPos.y;
    totalAirDist += Math.sqrt(dxAir * dxAir + dyAir * dyAir);

    for (let i = 0; i < poly.points.length - 1; i++) {
      const p1 = poly.points[i];
      const p2 = poly.points[i + 1];
      const dx = p2.x - p1.x;
      const dy = p2.y - p1.y;
      totalDrawDist += Math.sqrt(dx * dx + dy * dy);
    }
    curPos = pEnd;
  }

  const travelTime = (totalAirDist / preset.travelFeedrate) * 60;
  const drawTime = (totalDrawDist / preset.drawFeedrate) * 60;
  const zHopHeight = Math.abs(preset.penUpZ - preset.penDownZ);
  const zTime = polylines.length * 2 * ((zHopHeight / preset.zFeedrate) * 60);
  const estimatedTimeSeconds = Math.round(travelTime + drawTime + zTime);

  const lines: string[] = [];
  let currentZ: number | null = null;

  // Helper to emit Z motion and suppress duplicate consecutive Z commands
  const emitZ = (targetZ: number, feedrate: number, isG1: boolean = false) => {
    if (currentZ !== null && Math.abs(currentZ - targetZ) < 0.0005) {
      return; // Suppress duplicate consecutive Z-hop command
    }
    const cmd = isG1 ? 'G1' : 'G0';
    lines.push(`${cmd} Z${targetZ.toFixed(3)} F${feedrate}`);
    currentZ = targetZ;
  };

  // 1. Mandatory Header
  const minX = validation.bounds.minNozzleX.toFixed(3);
  const maxX = validation.bounds.maxNozzleX.toFixed(3);
  const minY = validation.bounds.minNozzleY.toFixed(3);
  const maxY = validation.bounds.maxNozzleY.toFixed(3);

  lines.push('; Generated by PlotForge');
  lines.push(
    `; Machine: ${preset.name} | Pens: ${penCount} | Est Time: ${formatDuration(estimatedTimeSeconds)}`
  );
  lines.push(
    `; Nozzle Bounds: X[${minX}..${maxX}] Y[${minY}..${maxY}] Z[${preset.penDownZ.toFixed(3)}..${preset.safeParkZ.toFixed(3)}]`
  );

  // Guard 3D printer heater & fan commands for non-GRBL firmware
  if (preset.firmware !== 'grbl') {
    lines.push('M104 S0 ; Ensure hotend heater is OFF');
    lines.push('M140 S0 ; Ensure bed heater is OFF');
    lines.push('M107    ; Ensure part cooling fan is OFF');

    // Clamp acceleration to eliminate cantilever arm vibration and prevent ink starvation
    const drawAcc = preset.drawAcceleration ?? 1000;
    const travelAcc = preset.travelAcceleration ?? 1500;
    lines.push(
      `M204 P${drawAcc} T${travelAcc} ; Clamp draw & travel acceleration (prevents cantilever arm vibration & ink starvation)`
    );
    lines.push('M205 X6 Y6 Z3 ; Soft corner jerk limit: zero pen bounce, smooth handwriting turns');
  }

  lines.push('G21     ; Millimetre units');
  lines.push('G90     ; Absolute positioning');
  lines.push('G28     ; Home all axes WITHOUT PEN INSTALLED');

  // Move nozzle to safe height for hardware pause
  emitZ(preset.safeParkZ, preset.zFeedrate);

  const firstPenId = penKeys[0] || 'pen-1';
  const firstPen = penMap.get(firstPenId);
  const firstPenName = firstPen ? firstPen.name : 'Pen 1';

  if (preset.firmware === 'bambu') {
    lines.push('; --- BAMBU LAB HARDWARE PAUSE ---');
    lines.push('; Note: Bambu OS firmware automatically parks the toolhead over the poop chute (waste bin).');
    lines.push(`; Slide "${firstPenName}" into the PIP mount (nib extending ~10-12mm below nozzle with spring compliance).`);
    lines.push('; Once seated, press "Resume" on the printer touchscreen to start drawing on the bed.');
    lines.push(`${preset.pauseCommand} ; PAUSE: Toolhead parks at poop chute. Insert pen, then tap Resume`);
  } else {
    const safePause = getSafePenPausePosition(preset);
    lines.push(
      `G0 X${safePause.nozzleX.toFixed(3)} Y${safePause.nozzleY.toFixed(3)} F${preset.travelFeedrate}`
    );
    emitZ(preset.penDownZ + 0.5, preset.zFeedrate, true);
    lines.push(
      `${preset.pauseCommand} ; PAUSE: Insert pen "${firstPenName}", touch nib to paper, tighten mount, then Resume`
    );
  }
  emitZ(preset.penUpZ, preset.zFeedrate);

  // 2. Iterate each pen group
  penKeys.forEach((penId, groupIndex) => {
    const pen = penMap.get(penId);
    const penName = pen ? pen.name : `Pen (${penId})`;
    const groupPolylines = penGroups.get(penId) || [];
    const penDrawFeedrate =
      pen?.drawSpeedMmS && pen.drawSpeedMmS > 0 ? Math.round(pen.drawSpeedMmS * 60) : preset.drawFeedrate;
    const penDownZ = pen?.penDownZ !== undefined ? pen.penDownZ : preset.penDownZ;
    const penUpZ = pen?.penUpZ !== undefined ? pen.penUpZ : preset.penUpZ;
    const dwellMs = pen?.dwellDownMs && pen.dwellDownMs > 0 ? pen.dwellDownMs : 0;
    const toolMsg = pen?.toolChangeMessage || `Swap to pen "${penName}"`;

    if (groupIndex > 0) {
      // Pen swap routine
      lines.push('');
      lines.push(`; --- PEN SWAP: ${penName} ---`);
      emitZ(preset.safeParkZ, preset.zFeedrate);
      lines.push(`M117 ${toolMsg}`);
      if (preset.firmware === 'bambu') {
        lines.push(
          `${preset.pauseCommand} ; PAUSE: Toolhead parks at poop chute. Swap to pen "${penName}", then tap Resume`
        );
      } else {
        const safePause = getSafePenPausePosition(preset);
        lines.push(
          `G0 X${safePause.nozzleX.toFixed(3)} Y${safePause.nozzleY.toFixed(3)} F${preset.travelFeedrate}`
        );
        emitZ(penDownZ + 0.5, preset.zFeedrate, true);
        lines.push(
          `${preset.pauseCommand} ; PAUSE: Swap to pen "${penName}", touch nib to paper, tighten mount, then Resume`
        );
      }
      emitZ(penUpZ, preset.zFeedrate);
    }

    lines.push(`; Start drawing with ${penName} (${groupPolylines.length} strokes @ ${Math.round(penDrawFeedrate / 60)}mm/s)`);

    for (const poly of groupPolylines) {
      if (poly.points.length < 2) continue;

      const pStart = penToNozzle(
        poly.points[0].x,
        poly.points[0].y,
        preset.penOffsetX,
        preset.penOffsetY
      );

      // Travel to start at penUpZ (suppresses redundant Z moves if already at penUpZ)
      emitZ(penUpZ, preset.zFeedrate);
      lines.push(
        `G0 X${pStart.x.toFixed(3)} Y${pStart.y.toFixed(3)} F${preset.travelFeedrate}`
      );

      // Pen down
      emitZ(penDownZ, preset.zFeedrate, true);
      if (dwellMs > 0) {
        lines.push(`G4 P${dwellMs} ; Ink settle dwell`);
      }

      // Draw path with modal feedrate (emit F on first G1 move of each stroke)
      let isFirstG1 = true;
      let lastEmittedPt = pStart;

      for (let i = 1; i < poly.points.length; i++) {
        const pt = penToNozzle(
          poly.points[i].x,
          poly.points[i].y,
          preset.penOffsetX,
          preset.penOffsetY
        );
        const distFromLast = Math.hypot(pt.x - lastEmittedPt.x, pt.y - lastEmittedPt.y);
        // Suppress microscopic zero-length moves (< 0.005mm) to prevent ink dwell dots unless it's the final point
        if (distFromLast < 0.005 && i < poly.points.length - 1) {
          continue;
        }

        if (isFirstG1) {
          lines.push(
            `G1 X${pt.x.toFixed(3)} Y${pt.y.toFixed(3)} F${penDrawFeedrate}`
          );
          isFirstG1 = false;
        } else {
          lines.push(`G1 X${pt.x.toFixed(3)} Y${pt.y.toFixed(3)}`);
        }
        lastEmittedPt = pt;
      }

      // Pen lift at end of stroke
      emitZ(penUpZ, preset.zFeedrate);
    }
  });

  // 3. Mandatory End G-code
  const presentX = Math.max(preset.minSafeX, Math.min(preset.maxSafeX, 10));
  const presentY = Math.max(preset.minSafeY, Math.min(preset.maxSafeY, preset.bedDepth - 10));
  lines.push('');
  lines.push('; --- FINISH & PRESENT ---');
  emitZ(preset.safeParkZ, preset.zFeedrate);
  lines.push(`G0 X${presentX.toFixed(3)} Y${presentY.toFixed(3)} F${preset.travelFeedrate}`);

  // Stepper disable / Program end depending on firmware
  if (preset.firmware !== 'grbl') {
    lines.push('M84 ; Disable steppers');
  } else {
    lines.push('M2  ; Program end / rewind');
  }

  const gcode = lines.join('\n');

  return {
    gcode,
    lineCount: lines.length,
    penCount,
    isValid: validation.isValid,
    errors: validation.errors,
    estimatedTimeSeconds,
  };
}
