// Helper to create a slanted italic font
function createSlantedFont(base: HersheyFont, slant: number = 0.26): HersheyFont {
  const result: HersheyFont = {};
  for (const [char, glyph] of Object.entries(base)) {
    result[char] = {
      width: glyph.width + Math.round(20 * slant * 0.4),
      strokes: glyph.strokes.map((stroke) =>
        stroke.map(([x, y]) => [Math.round((x + y * slant) * 10) / 10, y])
      ),
    };
  }
  return result;
}

